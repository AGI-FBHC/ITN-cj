"""Database repository for knowledge_document table.

Manages document records in MySQL including:
- Creating document records (idempotent, keyed by document_key)
- Updating document fields (storage_key, status, content_sha256, ...)
- Content-hash based fast-path detection (content unchanged)
"""

from __future__ import annotations

import logging
import os
from datetime import datetime
from typing import Any, Optional

import pymysql
from pymysql.cursors import DictCursor

logger = logging.getLogger(__name__)

# MySQL connection configuration (shared with images/repository.py)
MYSQL_CONFIG = {
    "host": os.environ.get("MYSQL_HOST"),
    "port": int(os.environ.get("MYSQL_PORT", 3306)),
    "user": os.environ.get("MYSQL_USER"),
    "password": os.environ.get("MYSQL_PASSWORD"),
    "database": os.environ.get("MYSQL_DATABASE"),
    "charset": "utf8mb4",
    "cursorclass": DictCursor,
    "connect_timeout": 15,
}


def get_connection() -> pymysql.Connection:
    """Get a MySQL database connection."""
    return pymysql.connect(**MYSQL_CONFIG)


def _insert_document(
    cursor: pymysql.cursors.Cursor,
    *,
    document_code: str,
    document_key: str,
    content_sha256: str,
    title: str,
    document_type: str,
    source_type: str,
    source_name: str,
    original_file_name: str,
    language: str,
    status: str,
    publisher: str = "",
    publish_year: int = 0,
    version: str = "",
    reliability_score: float = 0.0,
) -> None:
    """Insert a new knowledge_document row."""
    now = datetime.now()
    sql = """
        INSERT INTO knowledge_document (
            document_code, document_key, content_sha256, title, document_type,
            source_type, source_name, original_file_name, language, status,
            publisher, publish_year, version, reliability_score,
            created_at, updated_at
        ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
    """
    cursor.execute(sql, (
        document_code,
        document_key,
        content_sha256,
        title,
        document_type,
        source_type,
        source_name,
        original_file_name,
        language,
        status,
        publisher or None,
        publish_year or None,
        version or None,
        reliability_score or None,
        now,
        now,
    ))


def _update_document_cursor(
    cursor: pymysql.cursors.Cursor,
    document_id: int,
    **kwargs: Any,
) -> None:
    """Update arbitrary fields on a knowledge_document row (within an open transaction)."""
    if not kwargs:
        return
    set_parts = []
    values = []
    for field, value in kwargs.items():
        set_parts.append(f"{field} = %s")
        values.append(value)
    set_parts.append("updated_at = %s")
    values.append(datetime.now())
    values.append(document_id)
    sql = f"UPDATE knowledge_document SET {', '.join(set_parts)} WHERE id = %s"
    cursor.execute(sql, values)


def get_document_by_key(document_key: str) -> Optional[dict]:
    """Look up a document by its stable logical key."""
    conn = get_connection()
    try:
        with conn.cursor() as cursor:
            cursor.execute(
                "SELECT * FROM knowledge_document WHERE document_key = %s",
                (document_key,),
            )
            return cursor.fetchone()
    finally:
        conn.close()


