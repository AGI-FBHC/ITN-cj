def legacy_document_code(domain_id: str, file_hash: str) -> str:
    """The document_code generated by the legacy pipeline (content-hash based).

    e.g. domain_id='hello_agents', file_hash='sha256:c64a...' -> 'hello_agents_sha256:c'
    """
    return f"{domain_id}_{file_hash[:8]}"


def create_document(
    document_code: str,
    title: str,
    document_type: str,
    source_type: str,
    source_name: str,
    original_file_name: str,
    language: str = "zh-CN",
    status: str = "processing",
    publisher: str = "",
    publish_year: int = 0,
    version: str = "",
    reliability_score: float = 0.0,
) -> int:
    """DEPRECATED — legacy entry used by pipeline.py / web.app.py (/api/run).

    Insert a knowledge_document record, upserting by document_code.
    New code should use :func:`get_or_create_document` (stable document_key).
    """
    conn = get_connection()
    try:
        with conn.cursor() as cursor:
            sql = """
                INSERT INTO knowledge_document (
                    document_code, title, document_type,
                    source_type, source_name, original_file_name,
                    language, status, publisher, publish_year,
                    version, reliability_score,
                    created_at, updated_at
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                ON DUPLICATE KEY UPDATE
                    title = VALUES(title),
                    document_type = VALUES(document_type),
                    status = VALUES(status),
                    publisher = VALUES(publisher),
                    publish_year = VALUES(publish_year),
                    version = VALUES(version),
                    reliability_score = VALUES(reliability_score),
                    updated_at = VALUES(updated_at)
            """
            now = datetime.now()
            cursor.execute(sql, (
                document_code,
                title,
                document_type,
                source_type,
                source_name,
                original_file_name,
                language,
                status,
                publisher or None,
                publish_year or None,
                version or None,
                reliability_score or None,
                now,
                now,
            ))
            conn.commit()
            if cursor.lastrowid:
                return cursor.lastrowid
            cursor.execute(
                "SELECT id FROM knowledge_document WHERE document_code = %s",
                (document_code,),
            )
            row = cursor.fetchone()
            return row["id"]
    finally:
        conn.close()


def get_or_create_document(
    *,
    domain_id: str,
    document_key: str,
    file_hash: str,
    title: str,
    document_type: str,
    source_type: str,
    source_name: str,
    original_file_name: str,
    language: str = "zh-CN",
    status: str = "processing",
    publisher: str = "",
    publish_year: int = 0,
    version: str = "",
    reliability_score: float = 0.0,
) -> dict:
    """Idempotently get or create a knowledge_document record.

    Lookup order:
      1. stable document_key (new scheme)          -> reuse (content diff decides next steps)
      2. legacy hash-based document_code            -> migrate row in place (keep children)
      3. none                                       -> insert new row

    Returns a dict:
      - db_id: int
      - created_new: bool
      - content_unchanged: bool (existing row had the same content_sha256)
      - status: current status of the row
      - row: full row
    """
    # knowledge_document.document_code 是 varchar(64)，document_key 可能带完整路径超长
    document_code = document_key
    if len(document_code) > 64:
        document_code = f"{document_code[:55].rstrip('_')}_{file_hash[:8]}"

    conn = get_connection()
    try:
        with conn.cursor() as cursor:
            # 1. Stable key lookup
            cursor.execute(
                "SELECT * FROM knowledge_document WHERE document_key = %s",
                (document_key,),
            )
            row = cursor.fetchone()

            if row is None:
                # 2. Legacy hash-based code lookup
                legacy_code = legacy_document_code(domain_id, file_hash)
                cursor.execute(
                    "SELECT * FROM knowledge_document WHERE document_code = %s",
                    (legacy_code,),
                )
                row = cursor.fetchone()
                if row is not None:
                    # Migrate in place: keep children (chunks/figures) tied to this id
                    _update_document_cursor(
                        cursor,
                        row["id"],
                        document_code=document_code,
                        document_key=document_key,
                        content_sha256=file_hash,
                        title=title,
                        document_type=document_type,
                        source_type=source_type,
                        source_name=source_name,
                        original_file_name=original_file_name,
                        language=language,
                        publisher=publisher or None,
                        publish_year=publish_year or None,
                        version=version,
                        reliability_score=reliability_score or None,
                    )
                    conn.commit()
                    cursor.execute(
                        "SELECT * FROM knowledge_document WHERE id = %s",
                        (row["id"],),
                    )
                    row = cursor.fetchone()
                    return {
                        "db_id": row["id"],
                        "created_new": False,
                        "content_unchanged": (row.get("content_sha256") == file_hash),
                        "status": row["status"],
                        "row": row,
                    }

                # 3. Create new
                _insert_document(
                    cursor,
                    document_code=document_code,
                    document_key=document_key,
                    content_sha256=file_hash,
                    title=title,
                    document_type=document_type,
                    source_type=source_type,
                    source_name=source_name,
                    original_file_name=original_file_name,
                    language=language,
                    status=status,
                    publisher=publisher,
                    publish_year=publish_year,
                    version=version,
                    reliability_score=reliability_score,
                )
                conn.commit()
                new_id = cursor.lastrowid
                return {
                    "db_id": new_id,
                    "created_new": True,
                    "content_unchanged": False,
                    "status": status,
                    "row": {"id": new_id, "status": status, "content_sha256": file_hash},
                }

            # 1b. Existing by key: refresh content tracking
            content_unchanged = (row.get("content_sha256") == file_hash)
            _update_document_cursor(
                cursor,
                row["id"],
                content_sha256=file_hash,
                title=title,
                original_file_name=original_file_name,
                language=language,
                publisher=publisher or None,
                publish_year=publish_year or None,
                version=version,
                reliability_score=reliability_score or None,
            )
            if not content_unchanged and row["status"] not in ("processing", "failed"):
                # Content changed: reset to processing so incremental steps run
                _update_document_cursor(cursor, row["id"], status="processing")
            conn.commit()
            row["content_sha256"] = file_hash
            return {
                "db_id": row["id"],
                "created_new": False,
                "content_unchanged": content_unchanged,
                "status": row["status"] if content_unchanged else "processing",
                "row": row,
            }
    finally:
        conn.close()


def update_document_fields(document_id: int, **kwargs: Any) -> None:
    """Update arbitrary fields on a knowledge_document record."""
    if not kwargs:
        return

    conn = get_connection()
    try:
        with conn.cursor() as cursor:
            _update_document_cursor(cursor, document_id, **kwargs)
            conn.commit()
    finally:
        conn.close()


def get_document_fields(document_id: int) -> Optional[dict]:
    """Fetch the full row of a document."""
    conn = get_connection()
    try:
        with conn.cursor() as cursor:
            cursor.execute(
                "SELECT * FROM knowledge_document WHERE id = %s",
                (document_id,),
            )
            return cursor.fetchone()
    finally:
        conn.close()


def mark_document_failed(document_id: int, error: str) -> None:
    """Mark a document as failed with an error message."""
    update_document_fields(document_id, status="failed", last_error=str(error)[:2000])


def clear_document_error(document_id: int) -> None:
    """Clear the last error message."""
    update_document_fields(document_id, last_error=None)
